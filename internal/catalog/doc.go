package catalog

import (
	"fmt"
	"strings"
)

// reasonDocs says, for each reason, what the cards are and what it takes to
// add them to the pool.
var reasonDocs = map[Reason]struct {
	title string
	body  string
}{
	ReasonGigantic: {
		"Gigantic creatures",
		"A gigantic creature has two halves with one name. The base half has the power, " +
			"armor and text. The art half has none. To add them, build one pool card from " +
			"the base half and give it a type the page can show. Then give them an image " +
			"rule, because the art spans both halves.",
	},
	ReasonEvilTwin: {
		"Evil twins",
		"Each evil twin has the name of a regular creature that is in the pool. vex " +
			"records no power or armor for evil twins. To add them, get their stats into " +
			"vex's catalog. Then give the pool a rule for two cards with one name, so that " +
			"a guess can tell them apart.",
	},
	ReasonToken: {
		"Token creatures",
		"A token creature is not a deck card. A card in the deck makes it. vex records " +
			"no power or armor for token creatures. To add them, get their stats into " +
			"vex's catalog. Then convert them as creatures.",
	},
}

// ExcludedDoc renders the Markdown page that explains the excluded list.
func ExcludedDoc(res Result, jsonName string) []byte {
	counts := map[Reason]int{}
	for _, e := range res.Excluded {
		counts[e.Reason]++
	}

	var b strings.Builder

	b.WriteString("<!-- Code generated by `mage cards`. DO NOT EDIT. -->\n\n")
	b.WriteString("# Cards left out of the pool\n\n")
	fmt.Fprintf(&b, "The pool holds %d cards: the actions, artifacts, creatures and upgrades "+
		"of every deck, the Keyraken adventure's included, and the archon powers, prophecies "+
		"and tide that sit beside a deck. `mage cards` leaves %d cards out. ",
		len(res.Pool), len(res.Excluded))
	fmt.Fprintf(&b, "[%s](%s) lists each one. An entry is one card. Its `set` and `number` "+
		"are its first printing, and `printings` lists every catalog entry that it covers.\n\n",
		jsonName, jsonName)

	b.WriteString("| Reason | Cards |\n| --- | --- |\n")

	for _, r := range Reasons {
		fmt.Fprintf(&b, "| `%s` | %d |\n", r, counts[r])
	}

	for _, r := range Reasons {
		d := reasonDocs[r]
		fmt.Fprintf(
			&b,
			"\n## %s\n\nReason: `%s`. Cards: %d.\n\n%s\n",
			d.title,
			r,
			counts[r],
			d.body,
		)
	}

	return []byte(b.String())
}
